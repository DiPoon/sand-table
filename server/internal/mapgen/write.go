package mapgen

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
)

// Header is the comment at the top of both files.
func (m *Map) header() string {
	o := m.Opt
	return fmt.Sprintf("# Generated by sandtable-mapgen -name %s -seed %d -land %d -factions %d -spacing %g.\n"+
		"# Regenerate it rather than editing by hand.\n", o.Name, o.Seed, o.Land, o.Factions, o.Spacing)
}

// MapYAML returns the contents of data/maps/<name>.yaml.
func (m *Map) MapYAML() []byte {
	var b bytes.Buffer
	b.WriteString(m.header())
	fmt.Fprintf(&b, "# %d provinces (%d land), %d states. Coordinates and distances are km.\n\n", len(m.Provinces), len(m.landIndices()), len(m.States))
	b.WriteString("provinces:\n")
	for _, p := range m.Provinces {
		fmt.Fprintf(&b, "  - {id: %s, name: %s, terrain: %s, pos: [%d, %d]", p.Key, strconv.Quote(p.Name), p.Terrain, p.X, p.Y)
		if p.State >= 0 {
			fmt.Fprintf(&b, ", state: %s", m.States[p.State].Key)
		}
		if p.VP > 0 {
			fmt.Fprintf(&b, ", vp: %d", p.VP)
		}
		if p.Hub {
			b.WriteString(", hub: true")
		}
		b.WriteString("}\n")
	}
	b.WriteString("\n# [a, b, distance in km]\nedges:\n")
	for _, e := range m.Edges {
		fmt.Fprintf(&b, "  - [%s, %s, %d]\n", m.Provinces[e.A].Key, m.Provinces[e.B].Key, e.Dist)
	}
	b.WriteString("\nstates:\n")
	for _, s := range m.States {
		fmt.Fprintf(&b, "  - {id: %s, name: %s, capital: %s, manpower: %d, factories: %d, infrastructure: %d}\n",
			s.Key, strconv.Quote(s.Name), m.Provinces[s.Capital].Key, s.Manpower, s.Factories, s.Infrastructure)
	}
	b.WriteString("\n# [a, b, small | large]: a river along the border of a and b\nrivers:\n")
	for _, e := range m.Edges {
		if e.River > 0 {
			kind := "small"
			if e.River == 2 {
				kind = "large"
			}
			fmt.Fprintf(&b, "  - [%s, %s, %s]\n", m.Provinces[e.A].Key, m.Provinces[e.B].Key, kind)
		}
	}
	b.WriteString("\n# [a, b, level]\nrailways:\n")
	for _, e := range m.Edges {
		if e.Rail > 0 {
			fmt.Fprintf(&b, "  - [%s, %s, %d]\n", m.Provinces[e.A].Key, m.Provinces[e.B].Key, e.Rail)
		}
	}
	return b.Bytes()
}

// ScenarioYAML returns the contents of data/scenarios/<name>.yaml.
func (m *Map) ScenarioYAML() []byte {
	var b bytes.Buffer
	b.WriteString(m.header())
	fmt.Fprintf(&b, "\nmap: %s\n\nfactions:\n", m.Opt.Name)
	for _, f := range m.Factions {
		fmt.Fprintf(&b, "  - id: %s\n    name: %s\n    capital: %s\n    states: [", f.Key, strconv.Quote(f.Name), m.Provinces[f.Capital].Key)
		for k, s := range f.States {
			if k > 0 {
				b.WriteString(", ")
			}
			b.WriteString(m.States[s].Key)
		}
		b.WriteString("]\n")
	}
	b.WriteString("\n# Division IDs are assigned in this order, starting at 1.\ndivisions:\n")
	for _, d := range m.Divisions {
		fmt.Fprintf(&b, "  - {faction: %s, type: %s, name: %s, at: %s}\n",
			m.Factions[d.Faction].Key, d.Type, strconv.Quote(d.Name), m.Provinces[d.At].Key)
	}
	return b.Bytes()
}

// Write saves both files under dir (the data directory).
func (m *Map) Write(dir string) error {
	for _, f := range []struct {
		path string
		data []byte
	}{
		{filepath.Join(dir, "maps", m.Opt.Name+".yaml"), m.MapYAML()},
		{filepath.Join(dir, "scenarios", m.Opt.Name+".yaml"), m.ScenarioYAML()},
	} {
		if err := os.WriteFile(f.path, f.data, 0o644); err != nil {
			return err
		}
	}
	return nil
}
